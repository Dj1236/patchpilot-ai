"""A reviewable pull request proposal, built from the artifacts of a finished run.

Nothing is asked of a model here. The proposal is computed from the run's
record and the files the run started from: the patch is re-applied, its
diff is compared with the recorded one, and the patch rules are checked
again. Only a run that its own checks verified can be proposed.

What the proposal holds is what would be sent to GitHub, plus the identity
it is bound to. It never holds the hidden-test result, the trace, the
model's prompts or any credential: grading stays private to PatchPilot.
"""

import hashlib
import json
import os
from collections.abc import Iterable, Mapping
from datetime import UTC, datetime
from pathlib import Path
from typing import Literal

from pydantic import Field

from patchpilot.agent.baseline import RunLimits, RunRecord, RunStatus
from patchpilot.agent.report import _fenced, _quoted
from patchpilot.agent.trace import redact
from patchpilot.agent.verify import VerificationStep
from patchpilot.intake.allowlist import ApprovedRepository
from patchpilot.intake.github import is_safe_branch_name
from patchpilot.patch.apply import PatchError, apply_proposal, unified_diff
from patchpilot.patch.policy import check_policy
from patchpilot.sandbox.models import FrozenModel
from patchpilot.sandbox.tree import tree_digest
from patchpilot.tasks.integrity import is_test_path

PROPOSAL_FILE = "pr-proposal.json"
PROPOSAL_SUMMARY_FILE = "pr-proposal.md"
OPERATION = "create_draft_pull_request"
MAX_BODY_CHARS = 60_000
# What a reviewer must see in full. Larger proposals are refused, never cut.
MAX_DIFF_CHARS = 20_000
MAX_FILE_CHARS = 100_000
_SHA = r"^[0-9a-f]{40}$"


class ProposalError(ValueError):
    """A run cannot be proposed, or a stored proposal cannot be trusted."""


class FileChange(FrozenModel):
    path: str
    action: Literal["add", "modify"]
    content: str
    sha256: str
    is_test: bool


class PullRequestProposal(FrozenModel):
    schema_version: Literal[1] = 1
    repository: str
    repository_id: int = Field(ge=1)
    issue_number: int = Field(ge=1)
    base_branch: str
    base_commit: str = Field(pattern=_SHA)
    run_id: str
    task_id: str
    mode: str
    run_status: Literal["candidate_verified"] = "candidate_verified"
    record_sha256: str
    patch_sha256: str
    changes: tuple[FileChange, ...] = Field(min_length=1)
    diff: str
    validation: tuple[VerificationStep, ...]
    limitations: tuple[str, ...]
    branch: str
    title: str
    body: str = Field(max_length=MAX_BODY_CHARS)
    operation: Literal["create_draft_pull_request"] = "create_draft_pull_request"
    operations: tuple[str, ...]
    created_at: datetime


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def canonical(model: FrozenModel) -> bytes:
    return json.dumps(model.model_dump(mode="json"), sort_keys=True, separators=(",", ":")).encode()


def proposal_digest(proposal: PullRequestProposal) -> str:
    """The digest an approval is bound to: every field of the proposal."""
    return _sha256(canonical(proposal))


def patch_digest(base_commit: str, changes: Iterable[FileChange]) -> str:
    material = {"base": base_commit, "files": sorted((c.path, c.sha256) for c in changes)}
    return _sha256(json.dumps(material, sort_keys=True).encode())


LIMITATIONS = (
    "Generated by PatchPilot AI, an automated agent, and opened as a draft for review.",
    "Verified only by PatchPilot's own checks in a sandbox: the regression test was "
    "written by the same agent as the fix, and the results come from a process that "
    "runs the code under test.",
    "Not independently reviewed. Review the change and its test before merging.",
)


def _body(record: RunRecord, issue: int, changes: tuple[FileChange, ...], diff: str) -> str:
    if record.proposal is None or record.verification is None:
        raise ProposalError("the run has no verified proposal")
    rows = [
        f"| {step.name} | {step.expected} | {step.status.value} | {'yes' if step.ok else 'no'} |"
        for step in record.verification.steps
    ]
    tests = [change.path for change in changes if change.is_test]
    lines = [
        f"Proposed fix for #{issue}, prepared by PatchPilot AI.",
        "",
        "## What changed",
        "",
        *[f"- `{change.path}` ({change.action})" for change in changes],
        "",
        "## Agent's explanation",
        "",
        "Written by the agent. Shown as quoted text.",
        "",
        _quoted(record.proposal.summary),
        ">",
        _quoted(record.proposal.root_cause),
        "",
        "## Validation in a sandbox",
        "",
        f"Regression tests added: {', '.join(f'`{path}`' for path in tests) or 'none'}.",
        "",
        "| Check | Expected | Result | Holds |",
        "|---|---|---|---|",
        *rows,
        "",
        "## Limitations",
        "",
        *[f"- {item}" for item in LIMITATIONS],
        "",
        "## Diff",
        "",
        _fenced(diff, "diff"),
        "",
    ]
    body = "\n".join(lines)
    if len(body) > MAX_BODY_CHARS:
        raise ProposalError("the pull request body would be too long to show in full")
    return body


def build_proposal(
    record: RunRecord,
    record_bytes: bytes,
    files: Mapping[str, bytes],
    repository: ApprovedRepository,
    *,
    issue_number: int,
    base_branch: str,
    secrets: Iterable[str] = (),
    now: datetime | None = None,
) -> PullRequestProposal:
    """Build the proposal for a verified run. Raises ``ProposalError`` otherwise."""
    if record.status is not RunStatus.CANDIDATE_VERIFIED:
        raise ProposalError(f"only a verified run can be proposed; this one is {record.status}")
    verification, change = record.verification, record.proposal
    if verification is None or not verification.verified or change is None:
        raise ProposalError("the run has no verified proposal")
    pinned, recorded = repository.commit_sha, record.manifest.repository_commit
    if pinned and recorded and pinned != recorded:
        raise ProposalError("the run's commit is not the commit pinned for this repository")
    base_commit = pinned or recorded
    if base_commit is None:
        raise ProposalError("no base commit: pin one in the allowlist or run from a commit")
    if tree_digest(files) != record.manifest.repository_tree_sha256:
        raise ProposalError("these files are not the ones the run started from")
    if not is_safe_branch_name(base_branch):
        raise ProposalError("the base branch name is not safe")
    try:
        patched = apply_proposal(files, change)
    except PatchError as error:
        raise ProposalError(f"the run's patch no longer applies: {error.code}") from None
    diff = unified_diff(files, patched)
    if len(diff) > MAX_DIFF_CHARS:
        raise ProposalError("the diff is too large to review in full; it is not proposed")
    if diff != record.diff:
        raise ProposalError("re-applying the patch does not give the recorded diff")
    if check_policy(files, change, patched, RunLimits().policy):
        raise ProposalError("the patch breaks a patch rule")
    known = tuple(secrets)
    changes = tuple(
        FileChange(
            path=path,
            action="modify" if path in files else "add",
            content=patched[path].decode("utf-8"),
            sha256=_sha256(patched[path]),
            is_test=is_test_path(path),
        )
        for path in sorted(patched)
        if patched[path] != files.get(path)
    )
    if any(len(c.content) > MAX_FILE_CHARS for c in changes):
        raise ProposalError("a changed file is too large to review in full; it is not proposed")
    if any(redact(c.content, known) != c.content for c in changes):
        raise ProposalError("a changed file contains a known secret; it is not proposed")
    digest = patch_digest(base_commit, changes)
    branch = f"patchpilot/issue-{issue_number}-{digest[:12]}"
    operations = (
        f"Read {repository.slug}: repository id, push permission, branch {base_branch}",
        f"Create {len(changes)} blob(s), one tree and one commit on parent {base_commit[:12]}",
        f"Create branch {branch} (never {base_branch}, never a force push)",
        f"Open one draft pull request from {branch} into {base_branch}; nothing is merged",
    )
    return PullRequestProposal(
        repository=repository.slug,
        repository_id=repository.repository_id,
        issue_number=issue_number,
        base_branch=base_branch,
        base_commit=base_commit,
        run_id=record.run_id,
        task_id=record.task_id,
        mode=record.mode,
        record_sha256=_sha256(record_bytes),
        patch_sha256=digest,
        changes=changes,
        diff=redact(diff, known),
        validation=verification.steps,
        limitations=LIMITATIONS,
        branch=branch,
        title=f"PatchPilot: proposed fix for #{issue_number}",
        body=redact(_body(record, issue_number, changes, diff), known),
        operations=operations,
        created_at=now or datetime.now(UTC),
    )


def write_private(path: Path, text: str) -> None:
    """Replace a file atomically, readable by the owner only."""
    temporary = path.with_name(f".{path.name}.tmp")
    descriptor = os.open(temporary, os.O_CREAT | os.O_WRONLY | os.O_TRUNC | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, "w") as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())
    temporary.replace(path)


def _full_fence(text: str) -> str:
    """Fence ``text`` without shortening it: a reviewer sees every character pushed."""
    longest, run = 0, 0
    for char in text:
        run = run + 1 if char == "`" else 0
        longest = max(longest, run)
    fence = "`" * max(3, longest + 1)
    return f"{fence}\n{text}{'' if text.endswith(chr(10)) else chr(10)}{fence}"


def save_proposal(directory: Path, proposal: PullRequestProposal) -> None:
    write_private(directory / PROPOSAL_FILE, canonical(proposal).decode() + "\n")
    summary = "\n".join(
        [
            f"# Pull request proposal for {proposal.repository}#{proposal.issue_number}",
            "",
            f"- Run `{proposal.run_id}` ({proposal.mode}), status `{proposal.run_status}`",
            f"- Base `{proposal.base_branch}` at `{proposal.base_commit}`",
            f"- Patch digest `{proposal.patch_sha256}`",
            f"- Proposal digest `{proposal_digest(proposal)}`",
            "",
            "## Intended GitHub operations",
            "",
            *[f"{index}. {item}" for index, item in enumerate(proposal.operations, start=1)],
            "",
            f"## Title\n\n{proposal.title}\n\n## Body\n\n{proposal.body}",
            "",
            "## Every changed file, in full, as it will be pushed",
            "",
            *[
                f"### `{change.path}` ({change.action}, sha256 `{change.sha256}`)\n\n"
                f"{_full_fence(change.content)}\n"
                for change in proposal.changes
            ],
        ]
    )
    write_private(directory / PROPOSAL_SUMMARY_FILE, summary)


def load_proposal(directory: Path) -> PullRequestProposal:
    path = directory / PROPOSAL_FILE
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 8 * 1024 * 1024:
        raise ProposalError(f"{directory} has no usable pull request proposal")
    try:
        proposal = PullRequestProposal.model_validate_json(path.read_bytes())
    except ValueError:
        raise ProposalError("the stored proposal is not valid") from None
    if patch_digest(proposal.base_commit, proposal.changes) != proposal.patch_sha256:
        raise ProposalError("the stored proposal's files do not match its patch digest")
    for change in proposal.changes:
        if _sha256(change.content.encode()) != change.sha256:
            raise ProposalError(f"the stored content of {change.path} was changed")
    return proposal
